#!/usr/bin/env python3
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from app import routers  # noqa: E402
from app.agent_guide import tool_name, when  # noqa: E402
from app.engine.commands import REGISTRY  # noqa: E402

SKILLS = ROOT / ".claude" / "skills"
MIRROR = ROOT / ".agents" / "skills"
MCP_URL = "http://127.0.0.1:8490/mcp"
GROUPS = {
    "chat": "Chat with Claude", "conversation": "Chats", "message": "Chats", "artifact": "Artifacts", "files": "Chat files and outputs", "outputs": "Chat files and outputs",
    "tasks": "Chat files and outputs", "project": "Projects", "memory": "Memory", "skill": "Skills", "connector": "Connectors", "schedule": "Scheduled tasks",
    "background": "Scheduled tasks", "terminal": "Terminals", "native": "Terminals", "tool": "Approvals and questions", "settings": "Settings and keys",
    "models": "Settings and keys", "keys": "Settings and keys", "account": "Settings and keys", "agents": "Settings and keys", "app": "Settings and keys",
}
HEADER = "Generated by ./format agents sync from the engine's command registry; do not edit by hand, run the sync again after changing a command."


def clean(text: str) -> str:
    text = re.sub(r"<([^<>]{1,40})>", r"[\1]", text or "")
    return text.replace("—", ", ").replace("|", "/").replace("\n", " ").strip()


def specs() -> list:
    assert routers.COMMAND_MODULES
    return sorted(REGISTRY.values(), key=lambda s: (list(GROUPS.values()).index(GROUPS.get(s.id.split(".")[0], "Settings and keys")), s.id))


def params_of(s) -> str:
    if not s.params:
        return "none"
    out = []
    for name, p in s.params.items():
        mark = "" if p.get("required") else "?"
        out.append(f"`{name}{mark}` {p.get('type', 'any')}")
    return ", ".join(out)


def tools_md() -> str:
    lines = ["# Format tools", "", HEADER, "",
             "Every tool is one engine command. Read-only tools change nothing; for the others the window shows the change live. A parameter with ? is optional. Pass ids from earlier results rather than guessing them.", "",
             "## Contents", ""]
    lines += [f"- {g}" for g in dict.fromkeys(GROUPS.get(s.id.split('.')[0], 'Settings and keys') for s in specs())]
    group = None
    for s in specs():
        g = GROUPS.get(s.id.split(".")[0], "Settings and keys")
        if g != group:
            lines += ["", f"## {g}", ""]
            group = g
        kind = "read-only" if not s.mutates else "changes state"
        lines += [f"### {tool_name(s.id)}", "", f"{clean(s.description) or clean(s.label)} {clean(when(s.id))}", "",
                  f"- {kind} · command `{s.id}` · params: {params_of(s)}", ""]
    return "\n".join(lines).replace("\n\n\n", "\n\n") + "\n"


def tool_map_md() -> str:
    lines = ["# Tool map", "", HEADER, "", "## Contents", "", "- The table: every MCP tool, the engine command behind it, and the file that defines the command", "",
             "## The table", "", "| MCP tool | Command | Defined in | Kind |", "| --- | --- | --- | --- |"]
    for s in specs():
        mod = s.fn.__module__.replace(".", "/") + ".py"
        lines.append(f"| `{tool_name(s.id)}` | `{s.id}` | `backend/{mod}` | {'read' if not s.mutates else 'write'} |")
    return "\n".join(lines) + "\n"


def command_map_md() -> str:
    lines = ["# Command map", "", HEADER, "", "## Contents", "", "- The table: each engine command in its three forms, REST (POST /api/commands/[id] with a JSON body), CLI, and MCP", "",
             "## The table", "", "| Command | CLI | MCP tool | Label |", "| --- | --- | --- | --- |"]
    for s in specs():
        req = [n for n, p in s.params.items() if p.get("required")]
        cli = "./format cli " + s.id + "".join(f" {n}=..." for n in req)
        lines.append(f"| `{s.id}` | `{cli}` | `{tool_name(s.id)}` | {clean(s.label)} |")
    return "\n".join(lines) + "\n"


def write(path: Path, text: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def generated() -> tuple:
    return (("format-driving/references/tools.md", tools_md()), ("format-harness/references/tool-map.md", tool_map_md()),
            ("format-harness/references/command-map.md", command_map_md()))


def tree(folder: Path) -> dict:
    if not folder.is_dir():
        return {}
    return {p.relative_to(folder).as_posix(): p.read_bytes() for p in sorted(folder.rglob("*")) if p.is_file()}


def check() -> int:
    stale = []
    for rel, text in generated():
        path = SKILLS / rel
        if (SKILLS / rel.split("/")[0]).is_dir() and (not path.is_file() or path.read_text(encoding="utf-8") != text):
            stale.append((SKILLS / rel).relative_to(ROOT).as_posix())
    source, mirror = tree(SKILLS), tree(MIRROR)
    for rel in sorted(set(source) | set(mirror)):
        if source.get(rel) != mirror.get(rel):
            stale.append((MIRROR / rel).relative_to(ROOT).as_posix())
    if stale:
        print("[format] out of date (run ./format agents sync):")
        for rel in stale:
            print(f"  {rel}")
        return 1
    print(f"[format] {len(REGISTRY)} commands; the agent files are up to date")
    return 0


def sync() -> None:
    changed = []
    for rel, text in generated():
        if (SKILLS / rel.split("/")[0]).is_dir() and write(SKILLS / rel, text):
            changed.append(rel)
    if MIRROR.exists():
        shutil.rmtree(MIRROR)
    if SKILLS.is_dir():
        shutil.copytree(SKILLS, MIRROR)
    print(f"[format] {len(REGISTRY)} commands; regenerated: {', '.join(changed) or 'nothing changed'}")
    print(f"[format] mirrored {', '.join(sorted(p.name for p in MIRROR.iterdir())) if MIRROR.is_dir() else 'no skills'} to .agents/skills for Codex and other agents")


def install(user: bool) -> None:
    sync()
    for f, who in ((".mcp.json", "Claude Code (project server; approve it once when asked)"), (".cursor/mcp.json", "Cursor"),
                   (".codex/config.toml", "Codex (read when you trust this project)")):
        print(f"[format] {'ok  ' if (ROOT / f).is_file() else 'MISSING'} {f}: {who}")
    if not user:
        print("[format] add --user to also register Format for every folder: Codex's ~/.codex/config.toml and, if installed, Claude Code's user scope")
        return
    codex = Path.home() / ".codex" / "config.toml"
    text = codex.read_text(encoding="utf-8") if codex.is_file() else ""
    if "[mcp_servers.format]" in text:
        print(f"[format] {codex} already lists Format")
    else:
        codex.parent.mkdir(parents=True, exist_ok=True)
        launcher = ROOT / ("format.bat" if os.name == "nt" else "format")
        with codex.open("a", encoding="utf-8") as f:
            f.write(f'\n[mcp_servers.format]\ncommand = "{launcher.as_posix()}"\nargs = ["mcp"]\n')
        print(f"[format] added Format to {codex}")
    if shutil.which("claude"):
        r = subprocess.run(["claude", "mcp", "add", "--scope", "user", "--transport", "http", "format", MCP_URL], capture_output=True, text=True)
        print(f"[format] Claude Code: {(r.stdout or r.stderr).strip().splitlines()[0] if (r.stdout or r.stderr).strip() else 'done'}")
    else:
        print("[format] Claude Code is not on the PATH; this repo's .mcp.json covers it here")


def main() -> None:
    args = sys.argv[1:]
    sub = args[0] if args else "sync"
    if sub == "sync" and "--check" in args:
        raise SystemExit(check())
    if sub == "sync":
        sync()
    elif sub == "install":
        install("--user" in args)
    else:
        raise SystemExit("usage: ./format agents [sync [--check]|install [--user]]")


if __name__ == "__main__":
    main()
